// Regenerates src/lib/tenant/scoped-models.generated.ts from the Prisma schema.
//
// The tenant Prisma extension needs to know which models carry `orgId`. That
// list could be hand-written, but then adding a model and forgetting to
// register it produces a table with no isolation and no error — the exact
// failure mode multi-tenancy cannot have. So it is derived from the schema,
// and `npm test` fails when the checked-in file is stale.
//
//   node scripts/gen-tenant-models.mjs          write the file
//   node scripts/gen-tenant-models.mjs --check  exit 1 if it is out of date

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "prisma", "schema");
const outFile = join(root, "src", "lib", "tenant", "scoped-models.generated.ts");

/**
 * Models that declare `orgId` but are owned by the platform operator, not by
 * the tenant. They are read across tenants by the operator console and must
 * never have a tenant filter injected.
 */
const OPERATOR_OWNED = new Set([
  "ImpersonationGrant",
  "TenantUsageSnapshot",
  "TenantOnboardingTask",
]);

export function parseSchema() {
  const scoped = [];
  const nullableOrg = [];
  const operator = [];
  const global = [];

  for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".prisma"))) {
    const source = readFileSync(join(schemaDir, file), "utf8");
    const modelRe = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
    let match;
    while ((match = modelRe.exec(source)) !== null) {
      const [, name, body] = match;
      const orgField = body
        .split("\n")
        .map((line) => line.trim())
        .find((line) => /^orgId\s+String/.test(line));

      if (!orgField) {
        global.push(name);
      } else if (OPERATOR_OWNED.has(name)) {
        operator.push(name);
      } else if (orgField.includes("String?")) {
        nullableOrg.push(name);
      } else {
        scoped.push(name);
      }
    }
  }

  return {
    scoped: scoped.sort(),
    nullableOrg: nullableOrg.sort(),
    operator: operator.sort(),
    global: global.sort(),
  };
}

/** Prisma exposes `model Foo` as `prisma.foo`. */
function clientKey(model) {
  return model.charAt(0).toLowerCase() + model.slice(1);
}

function render({ scoped, nullableOrg, operator, global }) {
  const list = (names) =>
    names.map((n) => `  "${clientKey(n)}",`).join("\n") || "";

  return `// GENERATED by scripts/gen-tenant-models.mjs — do not edit by hand.
// Run \`node scripts/gen-tenant-models.mjs\` after changing the Prisma schema.

/**
 * Models the tenant extension filters by \`orgId\`.
 *
 * Derived from the schema so a new tenant-owned table cannot be added
 * without isolation: the model gets the column, this list follows, and
 * \`scoped-models.test.ts\` fails if it does not.
 */
export const TENANT_SCOPED_MODELS = new Set<string>([
${list(scoped)}
]);

/**
 * Tenant-owned models whose \`orgId\` is nullable — a shared platform row and
 * a tenant override live in the same table. Filtered as
 * \`OR [{ orgId }, { orgId: null }]\` on read, and always written with the
 * tenant's own id.
 */
export const TENANT_OPTIONAL_MODELS = new Set<string>([
${list(nullableOrg)}
]);

/**
 * Carry \`orgId\` but belong to the platform operator, not to a tenant. Never
 * filtered — the operator console reads them across every tenant.
 */
export const OPERATOR_OWNED_MODELS = new Set<string>([
${list(operator)}
]);

/**
 * Everything else: child rows isolated through a foreign key to a scoped
 * parent, plus the genuinely global tables (Permission, Organization, the
 * platform-operator identity tables).
 */
export const UNSCOPED_MODELS = new Set<string>([
${list(global)}
]);
`;
}

const parsed = parseSchema();
const rendered = render(parsed);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (current !== rendered) {
    console.error(
      "scoped-models.generated.ts is out of date. Run: node scripts/gen-tenant-models.mjs",
    );
    process.exit(1);
  }
  console.log("scoped-models.generated.ts is current.");
} else {
  writeFileSync(outFile, rendered);
  console.log(
    `Wrote ${outFile}\n` +
      `  tenant-scoped : ${parsed.scoped.length}\n` +
      `  optional org  : ${parsed.nullableOrg.length}\n` +
      `  operator-owned: ${parsed.operator.length}\n` +
      `  unscoped      : ${parsed.global.length}`,
  );
}
